import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parse, nextState} from './worker.mjs';
const counts = parse(readFileSync(process.argv[2] || new URL('./fixtures/enrollment-27944.html', import.meta.url), 'utf8'));
assert.equal(counts['Enrollment Seats Available'], 0);
assert.throws(()=>parse('<html>Please log in</html>'));
let state = nextState(null, counts, 1000, 'Course', '27944');
assert.equal(state.pending, null);
const open = {...counts, 'Enrollment Seats Available': 1};
state = nextState(state, open, 2000, 'Course', '27944');
assert.equal(state.seq, 1);
const original = state.pending;
state = nextState(state, open, 3000, 'Course', '27944');
assert.deepEqual(state.pending, original);
state.pending = null;
assert.equal(nextState(state, open, 4000, 'Course', '27944').pending, null);
state = nextState(state, counts, 5000, 'Course', '27944');
state = nextState(state, open, 6000, 'Course', '27944');
assert.equal(state.seq, 2);
assert.equal(nextState(state, open, 700000, 'Course', '27944').pending, null);
console.log('Parser, malformed page, transition, retry, deduplication, reopening and expiry checks passed.');
